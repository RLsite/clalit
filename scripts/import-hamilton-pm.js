const pageById = new Map(pages.map((page) => [page.id, page]));

// Flatten all PM systems below the Hamilton PM root. The existing IDs are kept
// so links/bookmarks to the current PM pages continue to work.
for (const page of pages) {
  if (page.id === ROOT) continue;
  if (pageById.has(page.id)) page.parent_id = ROOT;
}
